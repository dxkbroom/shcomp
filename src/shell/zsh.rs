//! zsh shims: one autoloaded file per command.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::Command;

use eyre::Result;

use crate::config::Config;
use crate::registry::Registry;
use crate::report::Finding;
use crate::source;

const MARKER: &str = "# @generated by shcomp; do not edit";

pub fn site_functions(config: &Config) -> Result<PathBuf> {
    match &config.settings.data_dir {
        Some(path) => Ok(path.join("zsh").join("site-functions")),
        None => crate::dirs::zsh_site_functions(),
    }
}

pub fn shim_path(config: &Config, command: &str) -> Result<PathBuf> {
    Ok(site_functions(config)?.join(format!("_{command}")))
}

pub fn render_shim(command: &str, aliases: &BTreeSet<String>) -> String {
    let ident = ident(command);
    let names = std::iter::once(command.to_string())
        .chain(aliases.iter().cloned())
        .collect::<Vec<_>>();
    let compdef = names.join(" ");
    format!(
        r#"#compdef {compdef}
{MARKER}
{fn_name}() {{
  emulate -L zsh
  # A vendor script may write an `_arguments` spec with its exclusion group
  # unquoted, as `(--no-build-cache)'--build-cache[...]'`. zsh parses the
  # leading `(` as a glob group, and under the default NOMATCH a word that
  # matches nothing aborts the whole completion. Suppressing the error lets the
  # literal word reach `_arguments`, which is what the vendor meant; without
  # this, a completion such as gradle's fails on every flag that has a negative
  # form, and the error belongs to the vendor, not to shcomp.
  setopt no_nomatch
  local bin=${{commands[{command}]-}}
  [[ -n $bin ]] || return 1
  if [[ $bin != ${{__shcomp_bin_{ident}-}} ]] || {{ [[ -n ${{__shcomp_script_{ident}-}} ]] && [[ ${{__shcomp_script_{ident}}} -ot $bin ]]; }}; then
    local script
    script=$(command shcomp load --shell zsh --command {command} --bin "$bin" 2>/dev/null) || return 1
    typeset -g __shcomp_bin_{ident}=$bin
    typeset -g __shcomp_script_{ident}=$script
    local saved=${{functions[{fn_name}]}}
    __shcomp_source_{ident}() {{ source -- "$script"; }}
    __shcomp_source_{ident}
    local body=${{_comps[{command}]-{fn_name}}}
    if (( ! $+functions[$body] )); then
      functions[{fn_name}]=$saved
      compdef {fn_name} {compdef}
      return 1
    fi
    functions[__shcomp_body_{ident}]=${{functions[$body]}}
    functions[{fn_name}]=$saved
    compdef {fn_name} {compdef}
  fi
  __shcomp_body_{ident} "$@"
}}
"#,
        fn_name = format!("_{command}"),
    )
}

fn ident(command: &str) -> String {
    let sanitized: String = command
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    let hash = source::sha256_hex(command.as_bytes());
    format!("{sanitized}_{}", &hash[..6])
}

/// What `install` did to one shim.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShimStatus {
    Wrote,
    UpToDate,
    Removed,
    WouldWrite,
    WouldRemove,
}

impl ShimStatus {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Wrote => "wrote",
            Self::UpToDate => "up-to-date",
            Self::Removed => "removed",
            Self::WouldWrite => "would write",
            Self::WouldRemove => "would remove",
        }
    }
}

/// One command's shim after a reconcile.
#[derive(Debug, Clone)]
pub struct InstallRow {
    pub command: String,
    pub shim: std::path::PathBuf,
    pub status: ShimStatus,
}

#[derive(Debug, Clone)]
pub struct InstallReport {
    pub rows: Vec<InstallRow>,
    pub fpath: std::path::PathBuf,
}

impl InstallReport {
    /// The row for one command, which is how `add` reports only what it changed.
    pub fn row(&self, command: &str) -> Option<&InstallRow> {
        self.rows.iter().find(|row| row.command == command)
    }
}

/// Reconcile shims for every expected command, writing only what differs.
///
/// A disabled selection is not expected, so its shim is removed; a command that
/// mise also completes still gets a shim, because shcomp owns completion for
/// what the user selected.
pub fn install(config: &Config, registry: &Registry, dry_run: bool) -> Result<InstallReport> {
    let expected = expected_commands(registry, config)?;
    let dir = site_functions(config)?;
    if !dry_run {
        std::fs::create_dir_all(&dir)?;
    }

    let mut report = InstallReport {
        rows: Vec::new(),
        fpath: dir.clone(),
    };

    for (command, aliases) in &expected {
        let path = shim_path(config, command)?;
        let content = render_shim(command, aliases);
        let status = match std::fs::read_to_string(&path) {
            Ok(existing) if existing == content => ShimStatus::UpToDate,
            _ if dry_run => ShimStatus::WouldWrite,
            _ => {
                write_atomic(&path, content.as_bytes())?;
                ShimStatus::Wrote
            }
        };
        tracing::info!(
            command = %command,
            status = status.as_str(),
            shim = %path.display(),
            "shim"
        );
        report.rows.push(InstallRow {
            command: command.clone(),
            shim: path,
            status,
        });
    }

    if dir.is_dir() {
        for entry in std::fs::read_dir(&dir)? {
            let path = entry?.path();
            let Some(command) = path
                .file_name()
                .and_then(|name| name.to_str())
                .and_then(|name| name.strip_prefix('_'))
            else {
                continue;
            };
            if !owned(&path) || expected.contains_key(command) {
                continue;
            }
            let status = if dry_run {
                ShimStatus::WouldRemove
            } else {
                std::fs::remove_file(&path)?;
                ShimStatus::Removed
            };
            report.rows.push(InstallRow {
                command: command.to_string(),
                shim: path,
                status,
            });
        }
    }

    Ok(report)
}

pub fn uninstall(config: &Config, dry_run: bool) -> Result<Vec<PathBuf>> {
    let dir = site_functions(config)?;
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut removed = Vec::new();
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        if !owned(&path) {
            continue;
        }
        if !dry_run {
            std::fs::remove_file(&path)?;
        }
        removed.push(path);
    }
    if !dry_run && dir.is_dir() && std::fs::read_dir(&dir)?.next().is_none() {
        let _ = std::fs::remove_dir(&dir);
    }
    Ok(removed)
}

fn expected_commands(
    registry: &Registry,
    config: &Config,
) -> Result<BTreeMap<String, BTreeSet<String>>> {
    let mut expected: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for selected in registry.selected(config)? {
        let command = selected.resolved.tool.name.clone();
        let entry = expected.entry(command).or_default();
        for alias in &selected.aliases {
            if alias != &selected.resolved.tool.name {
                entry.insert(alias.clone());
            }
        }
    }
    Ok(expected)
}

fn owned(path: &Path) -> bool {
    path.is_file() && std::fs::read_to_string(path).is_ok_and(|text| text.contains(MARKER))
}

fn write_atomic(path: &Path, bytes: &[u8]) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let temporary = path.with_extension(format!("tmp.{}", std::process::id()));
    std::fs::write(&temporary, bytes)?;
    std::fs::rename(&temporary, path)?;
    Ok(())
}

/// Whether mise's packslip loader already owns this command's completion.
///
/// Only asked at install time. A tool that mise did not install from a
/// packslip answers with an error, which is the signal to leave it to shcomp.
pub fn mise_owned(command: &str) -> bool {
    let bin = match source::resolve_binary(command) {
        Ok(bin) => source::real_path(&bin),
        Err(_) => return false,
    };
    let is_mise_install = source::mise_installs()
        .iter()
        .any(|(_, _, install)| bin.starts_with(source::real_path(install)));
    if !is_mise_install {
        return false;
    }
    let output = Command::new("mise")
        .args(["completion", "zsh", "--tool", command])
        .output();
    let Ok(output) = output else {
        return false;
    };
    if !output.status.success() || output.stdout.is_empty() {
        return false;
    }
    let stderr = String::from_utf8_lossy(&output.stderr);
    let owned = !stderr.contains("not installed from a packslip");
    tracing::debug!(command, owned, "mise packslip probe");
    owned
}

/// Read-only checks for the zsh install.
///
/// An error is something the user has to fix: a missing or foreign shim, or a
/// generator that fails. A warning is a state `install` resolves on its own, or
/// one that is expected: a stale alias, a stale shim, a command that is not on
/// PATH.
pub fn doctor(config: &Config, registry: &Registry, check: bool) -> Result<Vec<Finding>> {
    let mut findings = Vec::new();
    let expected = expected_commands(registry, config)?;
    let dir = site_functions(config)?;
    if !dir.is_dir() {
        findings.push(Finding::error(
            "zsh",
            format!("missing shim directory: {}", dir.display()),
        ));
    }

    for (command, aliases) in &expected {
        let path = shim_path(config, command)?;
        if !path.exists() {
            findings.push(Finding::error(
                "zsh",
                format!("{command}: missing shim; run `shcomp install`"),
            ));
            continue;
        }
        let text = std::fs::read_to_string(&path)?;
        if !text.contains(MARKER) {
            findings.push(Finding::error(
                "zsh",
                format!("{command}: {} is not a shcomp shim", path.display()),
            ));
            continue;
        }
        let compdef = text.lines().next().unwrap_or_default();
        let registered: BTreeSet<&str> = compdef.split_whitespace().collect();
        let missing = std::iter::once(command)
            .chain(aliases.iter())
            .filter(|name| !registered.contains(name.as_str()))
            .collect::<Vec<_>>();
        if !missing.is_empty() {
            findings.push(Finding::warn(
                "zsh",
                format!(
                    "{command}: shim is stale for {}; run `shcomp install`",
                    missing
                        .iter()
                        .map(|name| name.to_string())
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            ));
        }
        if check {
            match source::resolve_binary(command) {
                Ok(bin) => {
                    match crate::cache::load_or_generate(config, registry, command, "zsh", &bin) {
                        Ok(script) => {
                            findings.push(Finding::ok(
                                "zsh",
                                format!("{command}: generator ok ({})", script.display()),
                            ));
                            findings.push(smoke(config, registry, command));
                        }
                        Err(error) => findings.push(Finding::error(
                            "zsh",
                            format!("{command}: generator failed: {error}"),
                        )),
                    }
                }
                Err(_) => findings.push(Finding::warn("zsh", format!("{command}: not on PATH"))),
            }
        }
    }

    if dir.is_dir() {
        for entry in std::fs::read_dir(&dir)? {
            let path = entry?.path();
            if !owned(&path) {
                continue;
            }
            let Some(command) = path
                .file_name()
                .and_then(|name| name.to_str())
                .and_then(|name| name.strip_prefix('_'))
            else {
                continue;
            };
            if !expected.contains_key(command) {
                findings.push(Finding::warn(
                    "zsh",
                    format!(
                        "{command}: stale shim {}; run `shcomp install`",
                        path.display()
                    ),
                ));
            }
        }
    }

    Ok(findings)
}

/// Ask the real completion system for one candidate, so a vendor script that
/// dies inside a completion is reported rather than silently offering nothing.
///
/// The failure this catches is the vendor's, not shcomp's: an unquoted glob or
/// a helper that does not exist. The shim guards the first (gradle's case);
/// anything else shows up here as an error or an empty answer.
fn smoke(config: &Config, registry: &Registry, command: &str) -> Finding {
    let request = crate::complete::Request {
        tool: command.to_string(),
        version: None,
        words: vec![command.to_string(), String::new()],
        cword: None,
        shell: "zsh".to_string(),
    };
    match crate::complete::complete(config, registry, &request) {
        Ok(candidates) if candidates.is_empty() => Finding::warn(
            "zsh",
            format!(
                "{command}: smoke completion returned nothing; the vendor completion may be broken (run `shcomp complete-word {command} {command} \"\"`)"
            ),
        ),
        Ok(candidates) => Finding::ok(
            "zsh",
            format!(
                "{command}: smoke completion ok ({} candidate(s))",
                candidates.len()
            ),
        ),
        Err(error) => Finding::error(
            "zsh",
            format!("{command}: smoke completion failed: {error}"),
        ),
    }
}

/// The selected commands whose completion mise's packslip loader also provides.
///
/// shcomp writes its own shim for these; naming them in `doctor` is how a user
/// finds the duplicate stub that would otherwise compete in the shell.
pub fn mise_owned_commands(config: &Config, registry: &Registry) -> Result<Vec<String>> {
    let mut commands = Vec::new();
    for (command, _) in expected_commands(registry, config)? {
        if mise_owned(&command) {
            commands.push(command);
        }
    }
    Ok(commands)
}

pub fn fpath_line(config: &Config) -> Result<String> {
    let dir = site_functions(config)?;
    Ok(format!(
        "fpath=({} $fpath)",
        shell_quote(&dir.to_string_lossy())
    ))
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shim_contains_compdef_and_dispatch() {
        let aliases = BTreeSet::from(["github".to_string()]);
        let shim = render_shim("gh", &aliases);
        assert!(shim.starts_with("#compdef gh github\n"), "{shim}");
        assert!(shim.contains(MARKER), "{shim}");
        assert!(
            shim.contains("command shcomp load --shell zsh --command gh"),
            "{shim}"
        );
        assert!(shim.contains("__shcomp_body_"), "{shim}");
    }

    #[test]
    fn identifiers_are_stable_and_safe() {
        assert_eq!(ident("gh"), ident("gh"));
        assert_ne!(ident("a-b"), ident("a_b"));
        assert!(
            ident("a-b")
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_')
        );
    }
}
