//! fish shims: one autoloaded completion file per command name.
//!
//! fish has no per-command completion function to capture (ADR-0009), so the
//! file registers one dynamic rule. Its loader runs in the user's fish, checks
//! the resolved executable and the cached script with builtins, and asks
//! `shcomp load` only when they changed; the answer comes from one child fish
//! that sources the cached script and runs `complete --do-complete`.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use eyre::Result;

use super::{ident, shell_quote, write_atomic};
use crate::config::Config;
use crate::registry::Registry;
use crate::shell::{InstallRow, ShellReport, ShimStatus, expected_commands};

const MARKER: &str = "# @generated by shcomp; do not edit";

pub fn site_completions(config: &Config) -> Result<PathBuf> {
    match &config.settings.data_dir {
        Some(path) => Ok(path.join("fish").join("completions")),
        None => Ok(crate::dirs::data_dir()?.join("fish").join("completions")),
    }
}

pub fn shim_path(config: &Config, command: &str) -> Result<PathBuf> {
    Ok(site_completions(config)?.join(format!("{command}.fish")))
}

/// The one line a fish user adds to load this directory.
pub fn loading_line(config: &Config) -> Result<String> {
    Ok(format!(
        "set -p fish_complete_path {}",
        shell_quote(&site_completions(config)?.to_string_lossy())
    ))
}

/// One autoloaded file. `name` is what the user types; `lookup` is the command
/// whose executable is the version source when `name` is an alias with no path.
pub fn render_shim(name: &str, lookup: &str) -> String {
    let ident = ident(name);
    format!(
        r#"{MARKER}
# Rechecks the resolved executable on every Tab and answers through one child
# fish that sources the cached script, so a version switch is followed without
# re-sourcing anything in this shell. See `docs/adr/0009`.
function __shcomp_load_{ident}
    set -l bin (command -s {name})
    test -n "$bin"; or set bin (command -s {lookup})
    test -n "$bin"; or return
    if test "$bin" != "$__shcomp_bin_{ident}"; or test -z "$__shcomp_script_{ident}"; or test "$__shcomp_script_{ident}" -ot "$bin"
        set -g __shcomp_bin_{ident} "$bin"
        set -g __shcomp_script_{ident} (command shcomp load --shell fish --command {name} --bin "$bin" 2>/dev/null)
        test -n "$__shcomp_script_{ident}"; or return
    end
    set -l fishbin (status fish-path)
    set -l line (commandline --current-process --cut-at-cursor | string collect --allow-empty)
    $fishbin --no-config -c 'set -e fish_complete_path
source $argv[1]
complete --do-complete $argv[2]' -- $__shcomp_script_{ident} "$line"
end
complete -c {name} -f -e
complete -c {name} -f -a '(__shcomp_load_{ident})'
"#
    )
}

pub fn install(config: &Config, registry: &Registry, dry_run: bool) -> Result<ShellReport> {
    let expected = expected_commands(registry, config, "fish")?;
    let dir = site_completions(config)?;
    if !dry_run {
        std::fs::create_dir_all(&dir)?;
    }

    let mut report = ShellReport {
        shell: "fish",
        rows: Vec::new(),
        loading: Some(loading_line(config)?),
    };

    let mut expected_names: BTreeSet<String> = BTreeSet::new();
    for (command, aliases) in &expected {
        let mut status = ShimStatus::UpToDate;
        let mut shim = shim_path(config, command)?;
        for name in std::iter::once(command).chain(aliases.iter()) {
            expected_names.insert(name.clone());
            let path = shim_path(config, name)?;
            let content = render_shim(name, command);
            shim = path.clone();
            let this = match std::fs::read_to_string(&path) {
                Ok(existing) if existing == content => ShimStatus::UpToDate,
                _ if dry_run => ShimStatus::WouldWrite,
                _ => {
                    write_atomic(&path, content.as_bytes())?;
                    ShimStatus::Wrote
                }
            };
            if this.changed() {
                status = this;
            }
        }
        tracing::info!(
            shell = "fish",
            command = %command,
            status = status.as_str(),
            shim = %shim.display(),
            "shim"
        );
        report.rows.push(InstallRow {
            command: command.clone(),
            shim,
            status,
        });
    }

    if dir.is_dir() {
        for entry in std::fs::read_dir(&dir)? {
            let path = entry?.path();
            if !owned(&path) {
                continue;
            }
            let Some(name) = path
                .file_name()
                .and_then(|name| name.to_str())
                .and_then(|name| name.strip_suffix(".fish"))
            else {
                continue;
            };
            if expected_names.contains(name) {
                continue;
            }
            let status = if dry_run {
                ShimStatus::WouldRemove
            } else {
                std::fs::remove_file(&path)?;
                ShimStatus::Removed
            };
            report.rows.push(InstallRow {
                command: name.to_string(),
                shim: path,
                status,
            });
        }
    }

    Ok(report)
}

pub fn uninstall(config: &Config, dry_run: bool) -> Result<Vec<PathBuf>> {
    let dir = site_completions(config)?;
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut removed = Vec::new();
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        if !owned(&path) {
            continue;
        }
        if !dry_run {
            std::fs::remove_file(&path)?;
        }
        removed.push(path);
    }
    if !dry_run && dir.is_dir() && std::fs::read_dir(&dir)?.next().is_none() {
        let _ = std::fs::remove_dir(&dir);
    }
    Ok(removed)
}

/// Check the fish shims against the selection, as `zsh::doctor` does for zsh.
///
/// A missing or foreign shim for a command is an error; a missing alias shim,
/// a shim whose content no longer matches, and a shim for a command that is no
/// longer selected are warnings that `shcomp install` fixes.
pub fn doctor(
    config: &Config,
    registry: &Registry,
    check: bool,
) -> Result<Vec<crate::report::Finding>> {
    use crate::report::Finding;

    let mut findings = Vec::new();
    let expected = expected_commands(registry, config, "fish")?;
    let dir = site_completions(config)?;
    if !dir.is_dir() {
        findings.push(Finding::error(
            "fish",
            format!("missing shim directory: {}", dir.display()),
        ));
    }

    let mut expected_names: BTreeSet<String> = BTreeSet::new();
    for (command, aliases) in &expected {
        let mut command_ok = true;
        let mut stale = Vec::new();
        for name in std::iter::once(command).chain(aliases.iter()) {
            expected_names.insert(name.clone());
            let path = shim_path(config, name)?;
            let Ok(text) = std::fs::read_to_string(&path) else {
                if name == command {
                    findings.push(Finding::error(
                        "fish",
                        format!("{command}: missing shim; run `shcomp install`"),
                    ));
                    command_ok = false;
                } else {
                    stale.push(name.clone());
                }
                continue;
            };
            if !text.contains(MARKER) {
                findings.push(Finding::error(
                    "fish",
                    format!("{name}: {} is not a shcomp shim", path.display()),
                ));
                command_ok = command_ok && name != command;
                continue;
            }
            if text != render_shim(name, command) {
                stale.push(name.clone());
            }
        }
        if !stale.is_empty() {
            findings.push(Finding::warn(
                "fish",
                format!(
                    "{command}: shim is stale for {}; run `shcomp install`",
                    stale.join(", ")
                ),
            ));
        }
        if check && command_ok {
            findings.extend(check_command(config, registry, command));
        }
    }

    if dir.is_dir() {
        for entry in std::fs::read_dir(&dir)? {
            let path = entry?.path();
            if !owned(&path) {
                continue;
            }
            let Some(name) = path
                .file_name()
                .and_then(|name| name.to_str())
                .and_then(|name| name.strip_suffix(".fish"))
            else {
                continue;
            };
            if !expected_names.contains(name) {
                findings.push(Finding::warn(
                    "fish",
                    format!(
                        "{name}: stale shim {}; run `shcomp install`",
                        path.display()
                    ),
                ));
            }
        }
    }

    Ok(findings)
}

/// `doctor --check` for one command: run its fish generator, then one real
/// completion through a child fish when fish is installed.
fn check_command(
    config: &Config,
    registry: &Registry,
    command: &str,
) -> Vec<crate::report::Finding> {
    use crate::report::Finding;

    let Ok(bin) = crate::source::resolve_binary(command) else {
        return vec![Finding::warn("fish", format!("{command}: not on PATH"))];
    };
    match crate::cache::load_or_generate(config, registry, command, "fish", &bin) {
        Ok(script) => {
            let mut findings = vec![Finding::ok(
                "fish",
                format!("{command}: generator ok ({})", script.display()),
            )];
            if crate::source::resolve_binary("fish").is_ok() {
                findings.push(super::zsh::smoke(config, registry, command, "fish"));
            }
            findings
        }
        Err(error) => vec![Finding::error(
            "fish",
            format!("{command}: generator failed: {error}"),
        )],
    }
}

fn owned(path: &Path) -> bool {
    path.is_file() && std::fs::read_to_string(path).is_ok_and(|text| text.contains(MARKER))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_shim_rechecks_the_binary_and_registers_one_rule() {
        let shim = render_shim("gh", "gh");
        assert!(shim.contains("function __shcomp_load_gh_"), "{shim}");
        assert!(shim.contains("command -s gh"), "{shim}");
        assert!(shim.contains("test \"$__shcomp_script_"), "{shim}");
        assert!(
            shim.contains("complete -c gh -f -a '(__shcomp_load_gh_"),
            "{shim}"
        );
        assert!(shim.starts_with(MARKER), "{shim}");
    }

    #[test]
    fn an_alias_falls_back_to_the_canonical_executable() {
        let shim = render_shim("github", "gh");
        assert!(shim.contains("command -s github"), "{shim}");
        assert!(shim.contains("command -s gh"), "{shim}");
        assert!(shim.contains("--command github"), "{shim}");
    }

    #[test]
    fn the_loading_line_prepends_the_directory() {
        let line = "set -p fish_complete_path '/data/fish/completions'";
        assert!(line.contains("set -p fish_complete_path"));
    }
}
